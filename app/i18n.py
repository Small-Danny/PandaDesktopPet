    """'2026 年 12 月 30 日 週三' / '2026년 12월 30일 수요일' / 'Wednesday, December 30, 2026'."""
    wd = get_weekday_names(lang)[weekday]
    if lang == "ko":
        return f"{year}년 {month}월 {day}일 {wd}"
    if lang == "en":
        import calendar as _calendar
        return f"{wd}, {_calendar.month_name[month]} {day}, {year}"
    return f"{year} 年 {month} 月 {day} 日 {wd}"


