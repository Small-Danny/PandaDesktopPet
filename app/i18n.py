def t(key: str, lang: str = "zh_TW", **kwargs) -> str:
    """Translates key to target language with fallback to zh_TW, supporting optional kwargs formatting."""
    locale = LOCALES.get(lang, LOCALES["zh_TW"])
    pattern = locale.get(key, LOCALES["zh_TW"].get(key, key))
    if kwargs:
        try:
            return pattern.format(**kwargs)
        except Exception:
            return pattern
    return pattern


